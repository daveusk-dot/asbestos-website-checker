"""Read a firm CSV, audit each website, and write an updated copy of the sheet.

The source file is not modified. Blank website cells are left blank.
Nothing here sends email.
"""

from __future__ import annotations

import csv
import io
from pathlib import Path

from trade import TradeError

WEBSITE_COLUMNS = {"website", "url", "site"}


def run_batch(
    csv_path: Path | str,
    output_dir: Path | str,
    *,
    run_audit,
    default_trade: str = "asbestos_surveying",
    **audit_kwargs,
) -> dict:
    source = Path(csv_path)
    folder = Path(output_dir)
    folder.mkdir(parents=True, exist_ok=True)
    text = source.read_text(encoding="utf-8-sig")
    reader = csv.DictReader(io.StringIO(text))
    if not reader.fieldnames:
        raise ValueError(f"{source} has no header row.")
    fields = list(reader.fieldnames)
    website_key = next((name for name in fields if name.strip().lower() in WEBSITE_COLUMNS), None)
    if website_key is None:
        raise ValueError(f"{source} needs a website column.")
    for extra in ("audit_run_date", "audit_score"):
        if extra not in fields:
            fields.append(extra)
    rows = list(reader)

    results = []
    failures = []
    for row in rows:
        website = (row.get(website_key) or "").strip()
        if not website:
            results.append(_strings(row, fields))
            continue
        trade_id = (row.get("trade") or "").strip() or default_trade
        firm_name = (row.get("firm_name") or "").strip() or None
        slot = (row.get("test_slot") or "").strip() or None
        try:
            summary = run_audit(
                website,
                trade=trade_id,
                output_dir=folder,
                firm_name=firm_name,
                slot=slot,
                **audit_kwargs,
            )
        except (ValueError, TradeError) as exc:
            failures.append({"website": website, "error": str(exc)})
            _write_failure(folder, website, firm_name, slot, str(exc))
            print(f"{website}: {exc}")
            results.append(_strings(row, fields))
            continue
        updated = dict(row)
        updated["audit_run_date"] = summary["audited_at"]
        updated["audit_score"] = str(summary["score"])
        results.append(_strings(updated, fields))
        label = firm_name or website
        report = summary.get("markdown_path") or ""
        print(f"{label}: {summary['score']}/100  {report}")

    updated_path = folder / f"{source.stem}.updated.csv"
    with updated_path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        writer.writerows(results)
    return {
        "csv_path": str(updated_path),
        "audited": sum(1 for row in results if (row.get("audit_score") or "").strip() != ""),
        "skipped_blank": sum(1 for row in rows if not (row.get(website_key) or "").strip()),
        "failures": failures,
    }


def _strings(row: dict, fields: list[str]) -> dict:
    clean = {}
    for key in fields:
        value = row.get(key)
        clean[key] = "" if value is None else str(value)
    return clean


def _write_failure(folder: Path, website: str, firm_name: str | None, slot: str | None, message: str) -> None:
    from datetime import date

    from runner import output_stem

    stem = output_stem(website if "://" in website else "https://invalid.example/", firm_name or website, date.today(), slot)
    path = folder / f"{stem}.md"
    path.write_text(
        "\n".join(
            [
                "# Quick Website Audit Summary",
                "",
                f"**Site:** {website}",
                "",
                "## Overall",
                "",
                f"This row was not audited. {message}",
                "",
                "---",
                "*Generated by a lightweight automated audit tool. This report is automated and needs a manual review.*",
                "",
            ]
        ),
        encoding="utf-8",
    )
